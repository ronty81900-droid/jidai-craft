#   正本は「19枚 流用します」と言い続けていた（守られない約束）。
#   B を読んで○を付ければ、二度と食い違わない。
def e_ichiran(atai):
    b = yomu(NE, "docs", "Codex依頼文_説明書B_詳細版.md")
    tsukau = set(int(x) for x in re.findall(r"e(\d\d)", b))
    return [(n, mei, naka.format(**atai), "○" if n in tsukau else "－")
            for n, mei, naka, _sho in E]



def settei(kagi):
    """load.mcfunction の settei から1つ読む。無ければ落とす（黙って0にしない）。"""
    m = re.search(r"scoreboard players set %s settei (-?\d+)" % re.escape(kagi), LOAD)
    assert m, "settei に %s が無い" % kagi
    return int(m.group(1))


def iraibun_page(kumi):
    """依頼文A/B が申告しているページ数を読む。

    ★ 手で写さない。依頼文を直したら、正本も一緒に動く。
    """
    fai = {"A": "Codex依頼文_説明書A_遊び方.md",
           "B": "Codex依頼文_説明書B_詳細版.md"}[kumi]
    t = yomu(NE, "docs", fai)
    m = re.search(r"\*\*(\d+)ページ\*\*", t)
    assert m, "%s にページ数が無い" % fai
    return int(m.group(1))


def teisuu(src, mei):
    m = re.search(r"%s\s*=\s*(\d+)" % mei, src)
    assert m, "%s が見つからない" % mei
    return int(m.group(1))


def kuriage(n):
    return "{:,}".format(n)


